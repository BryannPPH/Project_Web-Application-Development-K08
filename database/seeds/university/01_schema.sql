CREATE TABLE campus.buildings (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(10) NOT NULL UNIQUE,
    name VARCHAR(120) NOT NULL,
    campus_name VARCHAR(80) NOT NULL,
    opened_on DATE,
    floors SMALLINT NOT NULL CHECK (floors BETWEEN 1 AND 30)
);

CREATE TABLE campus.rooms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    building_id SMALLINT NOT NULL REFERENCES campus.buildings(id),
    code VARCHAR(20) NOT NULL,
    floor SMALLINT NOT NULL CHECK (floor > 0),
    capacity INTEGER NOT NULL CHECK (capacity BETWEEN 1 AND 1000),
    room_type VARCHAR(24) NOT NULL CHECK (room_type IN ('classroom', 'laboratory', 'auditorium', 'office')),
    UNIQUE (building_id, code)
);

CREATE INDEX rooms_type_capacity_idx ON campus.rooms (room_type, capacity);

CREATE TABLE campus.academic_terms (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(12) NOT NULL UNIQUE,
    name VARCHAR(80) NOT NULL,
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT FALSE,
    CHECK (ends_on > starts_on)
);

CREATE TABLE people.persons (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    national_id VARCHAR(24) NOT NULL UNIQUE,
    full_name VARCHAR(160) NOT NULL,
    email VARCHAR(180) NOT NULL UNIQUE,
    gender CHAR(1) NOT NULL CHECK (gender IN ('M', 'F')),
    birth_date DATE NOT NULL,
    phone VARCHAR(24),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX persons_name_idx ON people.persons (full_name);
CREATE INDEX persons_birth_date_idx ON people.persons (birth_date);

CREATE TABLE people.addresses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    person_id BIGINT NOT NULL REFERENCES people.persons(id) ON DELETE CASCADE,
    label VARCHAR(24) NOT NULL DEFAULT 'home',
    address_line TEXT NOT NULL,
    city VARCHAR(80) NOT NULL,
    province VARCHAR(80) NOT NULL,
    postal_code VARCHAR(10) NOT NULL,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE
);

CREATE INDEX addresses_person_idx ON people.addresses (person_id);
CREATE UNIQUE INDEX addresses_one_primary_idx ON people.addresses (person_id) WHERE is_primary;

CREATE TABLE academics.faculties (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(10) NOT NULL UNIQUE,
    name VARCHAR(140) NOT NULL UNIQUE,
    established_year SMALLINT NOT NULL CHECK (established_year BETWEEN 1900 AND 2100)
);

CREATE TABLE academics.departments (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    faculty_id SMALLINT NOT NULL REFERENCES academics.faculties(id),
    code VARCHAR(12) NOT NULL UNIQUE,
    name VARCHAR(140) NOT NULL,
    office_email VARCHAR(180) NOT NULL UNIQUE,
    UNIQUE (faculty_id, name)
);

CREATE INDEX departments_faculty_idx ON academics.departments (faculty_id);

CREATE TABLE academics.programs (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id SMALLINT NOT NULL REFERENCES academics.departments(id),
    code VARCHAR(16) NOT NULL UNIQUE,
    name VARCHAR(160) NOT NULL,
    degree_level VARCHAR(16) NOT NULL CHECK (degree_level IN ('diploma', 'bachelor', 'master', 'doctorate')),
    accreditation VARCHAR(16) NOT NULL CHECK (accreditation IN ('unggul', 'baik_sekali', 'baik')),
    required_credits SMALLINT NOT NULL CHECK (required_credits BETWEEN 36 AND 180),
    UNIQUE (department_id, name, degree_level)
);

CREATE INDEX programs_department_idx ON academics.programs (department_id);

CREATE TABLE people.students (
    person_id BIGINT PRIMARY KEY REFERENCES people.persons(id) ON DELETE CASCADE,
    student_number VARCHAR(20) NOT NULL UNIQUE,
    program_id SMALLINT NOT NULL REFERENCES academics.programs(id),
    cohort_year SMALLINT NOT NULL CHECK (cohort_year BETWEEN 2000 AND 2100),
    status VARCHAR(16) NOT NULL CHECK (status IN ('active', 'leave', 'graduated', 'dropped')),
    admitted_on DATE NOT NULL
);

CREATE INDEX students_program_status_idx ON people.students (program_id, status);
CREATE INDEX students_cohort_idx ON people.students (cohort_year);

CREATE TABLE people.staff (
    person_id BIGINT PRIMARY KEY REFERENCES people.persons(id) ON DELETE CASCADE,
    employee_number VARCHAR(20) NOT NULL UNIQUE,
    department_id SMALLINT NOT NULL REFERENCES academics.departments(id),
    staff_type VARCHAR(20) NOT NULL CHECK (staff_type IN ('lecturer', 'researcher', 'administration')),
    academic_rank VARCHAR(32),
    hired_on DATE NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE INDEX staff_department_type_idx ON people.staff (department_id, staff_type);

CREATE TABLE academics.courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_id SMALLINT NOT NULL REFERENCES academics.departments(id),
    code VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(180) NOT NULL,
    course_number SMALLINT NOT NULL CHECK (course_number BETWEEN 100 AND 999),
    credits SMALLINT NOT NULL CHECK (credits BETWEEN 1 AND 8),
    level SMALLINT NOT NULL CHECK (level BETWEEN 1 AND 8),
    has_laboratory BOOLEAN NOT NULL DEFAULT FALSE,
    UNIQUE (department_id, course_number)
);

CREATE INDEX courses_department_level_idx ON academics.courses (department_id, level);

CREATE TABLE academics.curriculum_courses (
    program_id SMALLINT NOT NULL REFERENCES academics.programs(id) ON DELETE CASCADE,
    course_id BIGINT NOT NULL REFERENCES academics.courses(id) ON DELETE CASCADE,
    semester_recommended SMALLINT NOT NULL CHECK (semester_recommended BETWEEN 1 AND 12),
    is_mandatory BOOLEAN NOT NULL DEFAULT TRUE,
    PRIMARY KEY (program_id, course_id)
);

CREATE INDEX curriculum_courses_course_idx ON academics.curriculum_courses (course_id);

CREATE TABLE academics.course_prerequisites (
    course_id BIGINT NOT NULL REFERENCES academics.courses(id) ON DELETE CASCADE,
    prerequisite_course_id BIGINT NOT NULL REFERENCES academics.courses(id) ON DELETE CASCADE,
    minimum_grade CHAR(2) NOT NULL DEFAULT 'C' CHECK (minimum_grade IN ('A', 'AB', 'B', 'BC', 'C')),
    PRIMARY KEY (course_id, prerequisite_course_id),
    CHECK (course_id <> prerequisite_course_id)
);

CREATE TABLE academics.classes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES academics.courses(id),
    term_id SMALLINT NOT NULL REFERENCES campus.academic_terms(id),
    lecturer_id BIGINT NOT NULL REFERENCES people.staff(person_id),
    room_id BIGINT REFERENCES campus.rooms(id),
    section VARCHAR(8) NOT NULL,
    weekday SMALLINT NOT NULL CHECK (weekday BETWEEN 1 AND 6),
    starts_at TIME NOT NULL,
    capacity SMALLINT NOT NULL CHECK (capacity BETWEEN 5 AND 500),
    status VARCHAR(16) NOT NULL CHECK (status IN ('planned', 'open', 'closed', 'cancelled')),
    UNIQUE (term_id, course_id, section)
);

CREATE INDEX classes_term_course_idx ON academics.classes (term_id, course_id);
CREATE INDEX classes_lecturer_idx ON academics.classes (lecturer_id);
CREATE INDEX classes_room_schedule_idx ON academics.classes (room_id, weekday, starts_at);

CREATE TABLE academics.enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id BIGINT NOT NULL REFERENCES academics.classes(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES people.students(person_id),
    enrolled_at TIMESTAMPTZ NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('enrolled', 'completed', 'withdrawn', 'failed')),
    final_score NUMERIC(5,2) CHECK (final_score BETWEEN 0 AND 100),
    letter_grade CHAR(2) CHECK (letter_grade IN ('A', 'AB', 'B', 'BC', 'C', 'D', 'E')),
    UNIQUE (class_id, student_id)
);

CREATE INDEX enrollments_student_status_idx ON academics.enrollments (student_id, status);
CREATE INDEX enrollments_class_score_idx ON academics.enrollments (class_id, final_score);

CREATE TABLE academics.class_meetings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    class_id BIGINT NOT NULL REFERENCES academics.classes(id) ON DELETE CASCADE,
    meeting_number SMALLINT NOT NULL CHECK (meeting_number BETWEEN 1 AND 20),
    held_on DATE NOT NULL,
    topic VARCHAR(220) NOT NULL,
    UNIQUE (class_id, meeting_number)
);

CREATE INDEX class_meetings_date_idx ON academics.class_meetings (held_on);

CREATE TABLE academics.attendance (
    meeting_id BIGINT NOT NULL REFERENCES academics.class_meetings(id) ON DELETE CASCADE,
    student_id BIGINT NOT NULL REFERENCES people.students(person_id),
    status VARCHAR(12) NOT NULL CHECK (status IN ('present', 'late', 'excused', 'absent')),
    recorded_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (meeting_id, student_id)
);

CREATE INDEX attendance_student_status_idx ON academics.attendance (student_id, status);

CREATE TABLE admissions.applications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_number VARCHAR(24) NOT NULL UNIQUE,
    person_id BIGINT NOT NULL REFERENCES people.persons(id),
    term_id SMALLINT NOT NULL REFERENCES campus.academic_terms(id),
    admission_track VARCHAR(24) NOT NULL CHECK (admission_track IN ('achievement', 'national_test', 'independent')),
    status VARCHAR(20) NOT NULL CHECK (status IN ('draft', 'submitted', 'verified', 'accepted', 'rejected')),
    submitted_at TIMESTAMPTZ
);

CREATE INDEX applications_term_status_idx ON admissions.applications (term_id, status);
CREATE INDEX applications_person_idx ON admissions.applications (person_id);

CREATE TABLE admissions.application_choices (
    application_id BIGINT NOT NULL REFERENCES admissions.applications(id) ON DELETE CASCADE,
    priority SMALLINT NOT NULL CHECK (priority BETWEEN 1 AND 3),
    program_id SMALLINT NOT NULL REFERENCES academics.programs(id),
    PRIMARY KEY (application_id, priority),
    UNIQUE (application_id, program_id)
);

CREATE INDEX application_choices_program_idx ON admissions.application_choices (program_id);

CREATE TABLE admissions.documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    application_id BIGINT NOT NULL REFERENCES admissions.applications(id) ON DELETE CASCADE,
    document_type VARCHAR(32) NOT NULL CHECK (document_type IN ('identity', 'transcript', 'certificate', 'recommendation')),
    file_name VARCHAR(180) NOT NULL,
    verification_status VARCHAR(16) NOT NULL CHECK (verification_status IN ('pending', 'valid', 'invalid')),
    uploaded_at TIMESTAMPTZ NOT NULL,
    UNIQUE (application_id, document_type)
);

CREATE INDEX documents_verification_idx ON admissions.documents (verification_status);

CREATE TABLE finance.fee_types (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(16) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    default_amount NUMERIC(14,2) NOT NULL CHECK (default_amount >= 0)
);

CREATE TABLE finance.student_bills (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_number VARCHAR(30) NOT NULL UNIQUE,
    student_id BIGINT NOT NULL REFERENCES people.students(person_id),
    term_id SMALLINT NOT NULL REFERENCES campus.academic_terms(id),
    issued_on DATE NOT NULL,
    due_on DATE NOT NULL,
    total_amount NUMERIC(14,2) NOT NULL CHECK (total_amount >= 0),
    status VARCHAR(16) NOT NULL CHECK (status IN ('unpaid', 'partial', 'paid', 'overdue', 'cancelled')),
    UNIQUE (student_id, term_id),
    CHECK (due_on >= issued_on)
);

CREATE INDEX student_bills_term_status_idx ON finance.student_bills (term_id, status);
CREATE INDEX student_bills_student_idx ON finance.student_bills (student_id);

CREATE TABLE finance.bill_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bill_id BIGINT NOT NULL REFERENCES finance.student_bills(id) ON DELETE CASCADE,
    fee_type_id SMALLINT NOT NULL REFERENCES finance.fee_types(id),
    description VARCHAR(180) NOT NULL,
    amount NUMERIC(14,2) NOT NULL CHECK (amount >= 0),
    UNIQUE (bill_id, fee_type_id)
);

CREATE INDEX bill_items_fee_type_idx ON finance.bill_items (fee_type_id);

CREATE TABLE finance.payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_number VARCHAR(30) NOT NULL UNIQUE,
    bill_id BIGINT NOT NULL REFERENCES finance.student_bills(id),
    paid_at TIMESTAMPTZ NOT NULL,
    amount NUMERIC(14,2) NOT NULL CHECK (amount > 0),
    method VARCHAR(20) NOT NULL CHECK (method IN ('bank_transfer', 'virtual_account', 'card', 'cash')),
    status VARCHAR(16) NOT NULL CHECK (status IN ('pending', 'settled', 'failed', 'refunded'))
);

CREATE INDEX payments_bill_status_idx ON finance.payments (bill_id, status);
CREATE INDEX payments_paid_at_idx ON finance.payments (paid_at);

CREATE TABLE finance.scholarships (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(140) NOT NULL,
    sponsor VARCHAR(140) NOT NULL,
    coverage_percent NUMERIC(5,2) NOT NULL CHECK (coverage_percent > 0 AND coverage_percent <= 100)
);

CREATE TABLE finance.student_scholarships (
    student_id BIGINT NOT NULL REFERENCES people.students(person_id),
    scholarship_id SMALLINT NOT NULL REFERENCES finance.scholarships(id),
    starts_term_id SMALLINT NOT NULL REFERENCES campus.academic_terms(id),
    ends_term_id SMALLINT REFERENCES campus.academic_terms(id),
    status VARCHAR(16) NOT NULL CHECK (status IN ('active', 'completed', 'revoked')),
    PRIMARY KEY (student_id, scholarship_id, starts_term_id)
);

CREATE INDEX student_scholarships_status_idx ON finance.student_scholarships (status);

CREATE TABLE library.publishers (
    id SMALLINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(140) NOT NULL UNIQUE,
    country VARCHAR(80) NOT NULL
);

CREATE TABLE library.authors (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(160) NOT NULL,
    country VARCHAR(80) NOT NULL
);

CREATE INDEX authors_name_idx ON library.authors (name);

CREATE TABLE library.books (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isbn VARCHAR(20) NOT NULL UNIQUE,
    title VARCHAR(220) NOT NULL,
    publisher_id SMALLINT NOT NULL REFERENCES library.publishers(id),
    published_year SMALLINT NOT NULL CHECK (published_year BETWEEN 1900 AND 2100),
    category VARCHAR(60) NOT NULL,
    page_count INTEGER NOT NULL CHECK (page_count > 0)
);

CREATE INDEX books_category_year_idx ON library.books (category, published_year);
CREATE INDEX books_title_idx ON library.books (title);

CREATE TABLE library.book_authors (
    book_id BIGINT NOT NULL REFERENCES library.books(id) ON DELETE CASCADE,
    author_id BIGINT NOT NULL REFERENCES library.authors(id),
    author_order SMALLINT NOT NULL CHECK (author_order BETWEEN 1 AND 10),
    PRIMARY KEY (book_id, author_id),
    UNIQUE (book_id, author_order)
);

CREATE INDEX book_authors_author_idx ON library.book_authors (author_id);

CREATE TABLE library.book_copies (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id BIGINT NOT NULL REFERENCES library.books(id),
    barcode VARCHAR(30) NOT NULL UNIQUE,
    acquired_on DATE NOT NULL,
    location_code VARCHAR(24) NOT NULL,
    status VARCHAR(16) NOT NULL CHECK (status IN ('available', 'borrowed', 'repair', 'lost'))
);

CREATE INDEX book_copies_book_status_idx ON library.book_copies (book_id, status);

CREATE TABLE library.loans (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    copy_id BIGINT NOT NULL REFERENCES library.book_copies(id),
    borrower_id BIGINT NOT NULL REFERENCES people.students(person_id),
    borrowed_at TIMESTAMPTZ NOT NULL,
    due_at TIMESTAMPTZ NOT NULL,
    returned_at TIMESTAMPTZ,
    fine_amount NUMERIC(12,2) NOT NULL DEFAULT 0 CHECK (fine_amount >= 0),
    CHECK (due_at > borrowed_at),
    CHECK (returned_at IS NULL OR returned_at >= borrowed_at)
);

CREATE INDEX loans_borrower_date_idx ON library.loans (borrower_id, borrowed_at DESC);
CREATE INDEX loans_active_due_idx ON library.loans (due_at) WHERE returned_at IS NULL;

CREATE TABLE research.projects (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(24) NOT NULL UNIQUE,
    department_id SMALLINT NOT NULL REFERENCES academics.departments(id),
    principal_investigator_id BIGINT NOT NULL REFERENCES people.staff(person_id),
    title VARCHAR(240) NOT NULL,
    starts_on DATE NOT NULL,
    ends_on DATE,
    budget NUMERIC(16,2) NOT NULL CHECK (budget >= 0),
    status VARCHAR(16) NOT NULL CHECK (status IN ('proposed', 'active', 'completed', 'cancelled')),
    CHECK (ends_on IS NULL OR ends_on >= starts_on)
);

CREATE INDEX projects_department_status_idx ON research.projects (department_id, status);
CREATE INDEX projects_principal_investigator_idx ON research.projects (principal_investigator_id);

CREATE TABLE research.project_members (
    project_id BIGINT NOT NULL REFERENCES research.projects(id) ON DELETE CASCADE,
    staff_id BIGINT NOT NULL REFERENCES people.staff(person_id),
    member_role VARCHAR(32) NOT NULL,
    allocation_percent NUMERIC(5,2) NOT NULL CHECK (allocation_percent > 0 AND allocation_percent <= 100),
    PRIMARY KEY (project_id, staff_id)
);

CREATE INDEX project_members_staff_idx ON research.project_members (staff_id);

CREATE TABLE research.publications (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_id BIGINT REFERENCES research.projects(id) ON DELETE SET NULL,
    doi VARCHAR(100) UNIQUE,
    title VARCHAR(260) NOT NULL,
    publication_type VARCHAR(20) NOT NULL CHECK (publication_type IN ('journal', 'conference', 'book_chapter', 'patent')),
    published_on DATE NOT NULL,
    citation_count INTEGER NOT NULL DEFAULT 0 CHECK (citation_count >= 0)
);

CREATE INDEX publications_project_date_idx ON research.publications (project_id, published_on DESC);
CREATE INDEX publications_citations_idx ON research.publications (citation_count DESC);

CREATE TABLE research.publication_authors (
    publication_id BIGINT NOT NULL REFERENCES research.publications(id) ON DELETE CASCADE,
    staff_id BIGINT NOT NULL REFERENCES people.staff(person_id),
    author_order SMALLINT NOT NULL CHECK (author_order BETWEEN 1 AND 20),
    is_corresponding BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (publication_id, staff_id),
    UNIQUE (publication_id, author_order)
);

CREATE INDEX publication_authors_staff_idx ON research.publication_authors (staff_id);
